import type {
  Anomaly,
  AuditEntry,
  ConflictDraft,
  DispositionPlan,
  ExpertOpinion,
  FieldReview,
  PendingWrite,
  PlanBasis,
  PlanLifecycle,
  RevisionRef,
  TailingsDataset
} from './models'

/**
 * 异常处置统一版本链引擎。
 *
 * 规则：
 * 1. 异常、现场复核、专业意见、处置方案、审计共用同一条单调递增的版本链，
 *    每个写入动作都记录其「所见版本」baseVersion。
 * 2. 同一异常并发保存时先到者生效（baseVersion === 当前版本）；后到者（baseVersion < 当前版本）
 *    不覆盖已生效的签批与审计，原样保留为冲突草稿及其依据版本。
 * 3. 专业意见补充/撤回：未执行方案立即失效并重算（清空草稿回到调查中）；
 *    执行中方案保留原依据继续执行，并追加一条现场复核。
 * 4. 写入失败可从完整审阅版本（PendingWrite）恢复重放；按 writeId 幂等，重放不重复追加结论。
 */

export type WriteKind =
  | 'field-review'
  | 'opinion-add'
  | 'opinion-withdraw'
  | 'plan-save'
  | 'plan-approve'
  | 'plan-start'
  | 'emergency-link'
  | 'anomaly-close'

export interface WritePayloads {
  'field-review': { review: Omit<FieldReview, 'version' | 'baseVersion' | 'basisVersion'> }
  'opinion-add': { opinion: Omit<ExpertOpinion, 'baseVersion' | 'withdrawn'> }
  'opinion-withdraw': { opinionId: string; reason: string }
  'plan-save': { plan: Omit<DispositionPlan, 'planVersion' | 'lifecycle' | 'baseVersion' | 'basis' | 'approvedBy' | 'approvedAt'> }
  'plan-approve': { approver: string; note: string }
  'plan-start': { operator: string; note: string }
  'emergency-link': { note: string }
  'anomaly-close': { note: string }
}

/** 审阅人一次保存动作的完整审阅版本（失败后可据此原样恢复） */
export interface ReviewWrite<K extends WriteKind = WriteKind> {
  writeId: string
  anomalyId: string
  kind: K
  baseVersion: number
  payload: WritePayloads[K]
  operator: string
  note?: string
  at: string
}

export interface AppliedResult {
  dataset: TailingsDataset
  audit: AuditEntry
  revision: RevisionRef
}

export interface RejectedResult {
  dataset: TailingsDataset
  reason: string
  conflict: ConflictDraft | null
}

export type ApplyResult = AppliedResult | RejectedResult

export const isApplied = (result: ApplyResult): result is AppliedResult =>
  (result as AppliedResult).revision !== undefined

export const blankPlan = (id: string): DispositionPlan => ({
  id,
  action: '加密监测',
  owner: '',
  deadline: '',
  conditions: '',
  emergencyLinked: false,
  approvedBy: '',
  approvedAt: '',
  planVersion: 0,
  lifecycle: '待提交',
  baseVersion: 0,
  basis: null
})

const auditOf = (write: ReviewWrite, anomaly: Anomaly, action: string, detail: string): AuditEntry => ({
  id: `AUD-${write.writeId}`,
  entityId: anomaly.id,
  action,
  operator: write.operator,
  detail: `所见V${write.baseVersion} → V${anomaly.version}｜${detail}`,
  createdAt: write.at,
  version: anomaly.version,
  writeId: write.writeId
})

const revisionOf = (write: ReviewWrite, anomaly: Anomaly, summary: string): RevisionRef => ({
  version: anomaly.version,
  writeId: write.writeId,
  kind: write.kind,
  operator: write.operator,
  summary,
  at: write.at
})

const snapshotBasis = (anomaly: Anomaly, at: string): PlanBasis => ({
  reviewVersion: anomaly.fieldReviews[0]?.version ?? 0,
  opinionIds: anomaly.opinions.filter((item) => !item.withdrawn).map((item) => item.id),
  opinionAt: at
})

/** 未执行方案：意见变动后立即失效并归档，方案重算（回到调查中） */
const invalidatePendingPlan = (anomaly: Anomaly, write: ReviewWrite, reason: string): AuditEntry => {
  const old = anomaly.plan
  anomaly.planHistory.unshift({ ...old })
  anomaly.plan = blankPlan(old.id)
  if (anomaly.status === '待负责人审批' || anomaly.status === '应急联动') anomaly.status = '原因调查中'
  const entry: AuditEntry = {
    id: `AUD-${write.writeId}-invalidate`,
    entityId: anomaly.id,
    action: '方案依据失效重算',
    operator: write.operator,
    detail: `方案V${old.planVersion}（${old.action}）因${reason}未执行即失效，回到原因调查中重算`,
    createdAt: write.at,
    version: anomaly.version,
    writeId: write.writeId
  }
  return entry
}

/** 执行中方案：保留原依据继续执行，追加一条现场复核 */
const appendRunningReview = (anomaly: Anomaly, write: ReviewWrite, reason: string): void => {
  const reviewNo = anomaly.fieldReviews.length + 1
  const review: FieldReview = {
    id: `FR-AUTO-${write.writeId}`,
    inspector: write.operator,
    arrivedAt: write.at,
    observed: `专业意见${reason}。执行中方案V${anomaly.plan.planVersion}保留签批时原依据继续执行，追加现场复核确认工况。`,
    evidence: `原依据复核版本V${anomaly.plan.basis?.reviewVersion ?? 0}；在案意见${anomaly.plan.basis?.opinionIds.join('、') || '无'}`,
    reassessment: '维持原执行依据，待追加复核结论后再决定是否调整方案。',
    version: reviewNo,
    baseVersion: write.baseVersion,
    basisVersion: anomaly.version,
    autoGenerated: true
  }
  anomaly.fieldReviews.unshift(review)
}

/** 同一 writeId 重放：已在链上或已留为冲突草稿，直接幂等返回，不重复追加结论 */
const alreadySeen = (anomaly: Anomaly, writeId: string): boolean =>
  anomaly.revisions.some((item) => item.writeId === writeId) ||
  anomaly.conflictDrafts.some((item) => item.writeId === writeId)

const validate = (anomaly: Anomaly | undefined, write: ReviewWrite): string => {
  if (!anomaly) return '异常不存在'
  if (anomaly.status === '已关闭') return '异常已关闭，禁止再写入'
  switch (write.kind) {
    case 'field-review': {
      const { review } = write.payload as WritePayloads['field-review']
      if (!review.observed || !review.evidence || !review.reassessment) return '现场复核的观察、证据与重新评估均为必填'
      return ''
    }
    case 'opinion-add':
      if (!(write.payload as WritePayloads['opinion-add']).opinion.content) return '专业意见内容不能为空'
      return ''
    case 'opinion-withdraw': {
      const { opinionId } = write.payload as WritePayloads['opinion-withdraw']
      const opinion = anomaly.opinions.find((item) => item.id === opinionId)
      if (!opinion) return '待撤回的专业意见不存在'
      if (opinion.withdrawn) return '该专业意见已撤回'
      return ''
    }
    case 'plan-save': {
      const { plan } = write.payload as WritePayloads['plan-save']
      if (!plan.owner || !plan.deadline || !plan.conditions) return '责任方、截止时间与关闭条件均为必填'
      if (anomaly.plan.lifecycle === '已签批' || anomaly.plan.lifecycle === '执行中') {
        return `方案V${anomaly.plan.planVersion}已签批生效，禁止覆盖，需另起修订`
      }
      return ''
    }
    case 'plan-approve': {
      if (anomaly.plan.lifecycle !== '待审批') return '仅待审批方案可签批'
      if (anomaly.severity === '重大' && !anomaly.plan.emergencyLinked) return '重大异常方案须先完成应急联动方可签批'
      return ''
    }
    case 'plan-start':
      if (anomaly.plan.lifecycle !== '已签批') return '仅已签批方案可开始执行'
      return ''
    case 'emergency-link':
      if (anomaly.plan.lifecycle === '执行中' || anomaly.plan.lifecycle === '已完成') return '执行中/已完成方案不改变联动状态'
      return ''
    case 'anomaly-close': {
      const { note } = write.payload as WritePayloads['anomaly-close']
      if (!note.trim()) return '关闭说明不能为空'
      if (!anomaly.fieldReviews.length) return '缺少现场复核，不得关闭'
      if (anomaly.plan.lifecycle !== '执行中') return '方案须已签批并开始执行后方可关闭'
      return ''
    }
  }
}

/**
 * 应用一次审阅写入。
 * - baseVersion 与当前版本一致：先到写入生效，链版本 +1，追加审计与链节点。
 * - baseVersion 落后：后到写入保留为冲突草稿（含依据版本），已生效签批/审计不受影响。
 * - 校验不通过：拒绝并返回原因。
 * - writeId 已处理过：幂等返回既有结果，重放不重复追加。
 */
export function applyReviewWrite(input: TailingsDataset, write: ReviewWrite): ApplyResult {
  const dataset: TailingsDataset = structuredClone(input)
  const anomaly = dataset.anomalies.find((item) => item.id === write.anomalyId)
  if (!anomaly) return { dataset, reason: '异常不存在', conflict: null }

  // 幂等：失败重放时结论只追加一次
  if (alreadySeen(anomaly, write.writeId)) {
    const revision = anomaly.revisions.find((item) => item.writeId === write.writeId)
    if (revision) {
      const audit = dataset.audit.find((item) => item.writeId === write.writeId && !item.action.includes('失效'))
      return { dataset, audit: audit as AuditEntry, revision }
    }
    const draft = anomaly.conflictDrafts.find((item) => item.writeId === write.writeId) as ConflictDraft
    return { dataset, reason: draft.reason, conflict: draft }
  }

  const validationError = validate(anomaly, write)
  if (validationError) return { dataset, reason: validationError, conflict: null }

  // 乐观锁：后到的旧窗口不得覆盖已生效的签批与审计
  if (write.baseVersion !== anomaly.version) {
    const draft: ConflictDraft = {
      id: `CFT-${write.writeId}`,
      anomalyId: anomaly.id,
      writeId: write.writeId,
      kind: write.kind,
      operator: write.operator,
      baseVersion: write.baseVersion,
      currentVersion: anomaly.version,
      reason: `所见V${write.baseVersion}已过期，当前为V${anomaly.version}，先到版本已生效`,
      payload: write.payload as Record<string, unknown>,
      createdAt: write.at,
      resolved: false
    }
    anomaly.conflictDrafts.unshift(draft)
    return { dataset, reason: draft.reason, conflict: draft }
  }

  const sideEffectAudit: AuditEntry[] = []
  let summary = ''
  let action = ''
  let detail = ''

  switch (write.kind) {
    case 'field-review': {
      const { review } = write.payload as WritePayloads['field-review']
      const version = anomaly.fieldReviews.length + 1
      anomaly.fieldReviews.unshift({
        ...review,
        version,
        baseVersion: write.baseVersion,
        basisVersion: -1
      })
      if (anomaly.status === '待现场复核') anomaly.status = '原因调查中'
      action = '提交现场复核'
      detail = `现场复核V${version}：${review.reassessment}`
      summary = `现场复核 V${version}（${review.inspector}）`
      break
    }
    case 'opinion-add': {
      const { opinion } = write.payload as WritePayloads['opinion-add']
      const stored: ExpertOpinion = { ...opinion, baseVersion: write.baseVersion, withdrawn: false }
      anomaly.opinions.unshift(stored)
      action = '补充专业意见'
      detail = `${opinion.discipline}专家${opinion.specialist}｜${opinion.conclusion}：${opinion.content}`
      summary = `补充专业意见（${opinion.specialist}）`
      if (anomaly.plan.lifecycle === '执行中') {
        appendRunningReview(anomaly, write, '补充')
        detail += '；执行中方案保留原依据，已追加现场复核'
      } else if (anomaly.plan.lifecycle === '待审批' || anomaly.plan.lifecycle === '已签批') {
        sideEffectAudit.push(invalidatePendingPlan(anomaly, write, '补充专业意见'))
        detail += '；未执行方案立即失效并回到重算'
      }
      break
    }
    case 'opinion-withdraw': {
      const { opinionId, reason } = write.payload as WritePayloads['opinion-withdraw']
      const opinion = anomaly.opinions.find((item) => item.id === opinionId) as ExpertOpinion
      opinion.withdrawn = true
      action = '撤回专业意见'
      detail = `撤回${opinion.discipline}专家${opinion.specialist}的意见（${opinionId}）：${reason}`
      summary = `撤回专业意见（${opinion.specialist}）`
      if (anomaly.plan.lifecycle === '执行中') {
        appendRunningReview(anomaly, write, '撤回')
        detail += '；执行中方案保留原依据，已追加现场复核'
      } else if (anomaly.plan.lifecycle === '待审批' || anomaly.plan.lifecycle === '已签批') {
        sideEffectAudit.push(invalidatePendingPlan(anomaly, write, '撤回专业意见'))
        detail += '；未执行方案立即失效并回到重算'
      }
      break
    }
    case 'plan-save': {
      const { plan } = write.payload as WritePayloads['plan-save']
      if (anomaly.plan.planVersion > 0) anomaly.planHistory.unshift({ ...anomaly.plan })
      const planVersion = Math.max(anomaly.plan.planVersion, anomaly.planHistory[0]?.planVersion ?? 0) + 1
      anomaly.plan = {
        ...plan,
        planVersion,
        lifecycle: '待审批',
        baseVersion: write.baseVersion,
        basis: null,
        approvedBy: '',
        approvedAt: ''
      }
      anomaly.status = '待负责人审批'
      action = '提交处置方案'
      detail = `提交方案V${planVersion}：${plan.action}，责任方${plan.owner}，截止${plan.deadline}`
      summary = `提交处置方案 V${planVersion}（${plan.action}）`
      break
    }
    case 'plan-approve': {
      const { approver, note } = write.payload as WritePayloads['plan-approve']
      const plan = anomaly.plan
      plan.approvedBy = approver
      plan.approvedAt = write.at
      plan.lifecycle = '已签批'
      plan.basis = snapshotBasis(anomaly, write.at)
      action = '审批处置方案'
      detail = `签批方案V${plan.planVersion}：${note || '同意执行'}；锁定依据（复核V${plan.basis.reviewVersion}、意见${plan.basis.opinionIds.length}条）`
      summary = `签批方案 V${plan.planVersion}（${approver}）`
      break
    }
    case 'plan-start': {
      const { note } = write.payload as WritePayloads['plan-start']
      anomaly.plan.lifecycle = '执行中'
      action = '开始执行方案'
      detail = `方案V${anomaly.plan.planVersion}按签批依据开始执行：${note}`
      summary = `开始执行方案 V${anomaly.plan.planVersion}`
      break
    }
    case 'emergency-link': {
      const { note } = write.payload as WritePayloads['emergency-link']
      anomaly.plan.emergencyLinked = true
      anomaly.status = '应急联动'
      action = '启动应急联动'
      detail = note
      summary = '启动应急联动'
      break
    }
    case 'anomaly-close': {
      const { note } = write.payload as WritePayloads['anomaly-close']
      anomaly.status = '已关闭'
      anomaly.closedAt = write.at
      anomaly.plan.lifecycle = '已完成'
      action = '关闭异常'
      detail = note
      summary = '关闭异常'
      break
    }
  }

  anomaly.version += 1
  const audit = auditOf(write, anomaly, action, detail)
  const revision = revisionOf(write, anomaly, summary)
  anomaly.revisions.unshift(revision)
  dataset.audit.unshift(audit, ...sideEffectAudit)
  return { dataset, audit, revision }
}

/** 落库前暂存完整审阅版本；写入失败后凭此恢复重试 */
export function stashPendingWrite(input: TailingsDataset, write: ReviewWrite, error: string, at: string): TailingsDataset {
  const dataset = structuredClone(input)
  const pending: PendingWrite = {
    writeId: write.writeId,
    anomalyId: write.anomalyId,
    kind: write.kind,
    baseVersion: write.baseVersion,
    payload: write.payload as Record<string, unknown>,
    operator: write.operator,
    note: write.note ?? '',
    at: write.at,
    failedAt: at,
    lastError: error,
    attempts: 1
  }
  dataset.pendingWrites = [pending, ...dataset.pendingWrites.filter((item) => item.writeId !== write.writeId)]
  return dataset
}

/**
 * 从完整审阅版本恢复并重试。
 * 沿用原始 writeId 与窗口时间戳：已生效则幂等不重复追加；过期则保留冲突草稿。
 */
export function retryPendingWrite(input: TailingsDataset, writeId: string, at: string): { dataset: TailingsDataset; result: ApplyResult; pending?: PendingWrite } {
  const stored = input.pendingWrites.find((item) => item.writeId === writeId)
  if (!stored) return { dataset: input, result: { dataset: input, reason: '未找到待恢复的审阅版本', conflict: null } }

  const write: ReviewWrite = {
    writeId: stored.writeId,
    anomalyId: stored.anomalyId,
    kind: stored.kind as WriteKind,
    baseVersion: stored.baseVersion,
    payload: stored.payload as WritePayloads[WriteKind],
    operator: stored.operator,
    note: stored.note,
    at: stored.at
  }
  const result = applyReviewWrite(input, write)

  if (isApplied(result) || result.conflict) {
    // 生效或已留冲突草稿都视为已落库，从待恢复队列移除
    const dataset: TailingsDataset = structuredClone(result.dataset)
    dataset.pendingWrites = dataset.pendingWrites.filter((item) => item.writeId !== writeId)
    return { dataset, result }
  }

  // 仍失败：保留完整版本并累计尝试次数，等待再次恢复
  const dataset: TailingsDataset = structuredClone(result.dataset)
  dataset.pendingWrites = dataset.pendingWrites.map((item) =>
    item.writeId === writeId ? { ...item, attempts: item.attempts + 1, lastError: result.reason, failedAt: at } : item
  )
  return { dataset, result, pending: dataset.pendingWrites.find((item) => item.writeId === writeId) }
}

/** 放弃冲突草稿（标记已处理，留痕不删） */
export function resolveConflictDraft(input: TailingsDataset, draftId: string): TailingsDataset {
  const dataset = structuredClone(input)
  const anomaly = dataset.anomalies.find((item) => item.conflictDrafts.some((draft) => draft.id === draftId))
  if (anomaly) {
    const draft = anomaly.conflictDrafts.find((item) => item.id === draftId)
    if (draft) draft.resolved = true
  }
  return dataset
}

/** 将冲突草稿作为一次新版本写入（审阅人已对照当前版本确认内容，所见版本更新为当前链版本） */
export function commitConflictDraft(input: TailingsDataset, draftId: string, operator: string, at: string): { dataset: TailingsDataset; result: ApplyResult } {
  const draft = input.anomalies.flatMap((item) => item.conflictDrafts).find((item) => item.id === draftId)
  if (!draft) return { dataset: input, result: { dataset: input, reason: '冲突草稿不存在', conflict: null } }
  const current = input.anomalies.find((item) => item.id === draft.anomalyId) as Anomaly
  const write: ReviewWrite = {
    writeId: `${draft.writeId}-R`,
    anomalyId: draft.anomalyId,
    kind: draft.kind as WriteKind,
    baseVersion: current.version,
    payload: draft.payload as WritePayloads[WriteKind],
    operator,
    note: `由冲突草稿${draft.id}（原所见V${draft.baseVersion}）核对V${current.version}后提交`,
    at
  }
  const result = applyReviewWrite(input, write)
  let dataset = result.dataset
  if (isApplied(result)) dataset = resolveConflictDraft(dataset, draftId)
  return { dataset, result }
}

export const lifecycleLabel = (lifecycle: PlanLifecycle): string => lifecycle
