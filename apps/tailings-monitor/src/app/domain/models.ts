export type MonitoringType = '位移' | '水位' | '渗流' | '降雨'
export type PointStatus = '正常' | '预警' | '异常'
export type AnomalyStatus = '待现场复核' | '原因调查中' | '待负责人审批' | '应急联动' | '已关闭'
export type Severity = '关注' | '较高' | '重大'

/** 处置方案生命周期：未执行（草稿/待审批/已签批/已失效）与执行中两大家族 */
export type PlanLifecycle = '待提交' | '待审批' | '已签批' | '执行中' | '已失效' | '已完成'

export interface MonitoringPoint {
  id: string
  name: string
  zone: string
  type: MonitoringType
  longitude: number
  latitude: number
  status: PointStatus
  currentValue: number
  unit: string
  thresholdId: string
  lastInspectionAt: string
}

export interface Threshold {
  id: string
  type: MonitoringType
  warning: number
  alarm: number
  changeRate: number
  unit: string
  enabled: boolean
  version: number
}

export interface RawReading {
  id: string
  pointId: string
  value: number
  unit: string
  capturedAt: string
  deviceId: string
  quality: '有效' | '可疑' | '无效'
}

/** 方案签批时锁定的依据快照：执行中方案在意见变动后仍按原依据执行 */
export interface PlanBasis {
  reviewVersion: number
  opinionIds: string[]
  opinionAt: string
}

export interface ExpertOpinion {
  id: string
  specialist: string
  discipline: '坝体' | '水文' | '岩土' | '应急'
  content: string
  conclusion: '支持结论' | '提出异议' | '补充证据'
  createdAt: string
  /** 写入该意见时审阅人所见的异常版本 */
  baseVersion: number
  /** 撤回后保留留痕，不再作为方案依据 */
  withdrawn: boolean
}

export interface FieldReview {
  id: string
  inspector: string
  arrivedAt: string
  observed: string
  evidence: string
  reassessment: string
  /** 复核自身在复核链中的序号 */
  version: number
  /** 写入时所见的异常版本（动作记录所见版本） */
  baseVersion: number
  /** 依据版本：人工复核记录为 -1；执行中意见变动追加的复核指向当时最新链版本 */
  basisVersion: number
  /** true 表示由"执行中保留原依据并追加复核"规则自动追加 */
  autoGenerated?: boolean
}

export interface DispositionPlan {
  id: string
  action: '加密监测' | '降低库水位' | '疏通排水' | '应急撤离准备' | '工程加固'
  owner: string
  deadline: string
  conditions: string
  emergencyLinked: boolean
  approvedBy: string
  approvedAt: string
  /** 方案独立版本号，每次重算/修订递增 */
  planVersion: number
  lifecycle: PlanLifecycle
  /** 提交时所见异常版本 */
  baseVersion: number
  /** 签批锁定的依据，执行中不被后续意见变动覆盖 */
  basis: PlanBasis | null
}

/** 版本链上的一个不可变版本节点 */
export interface RevisionRef {
  /** 链版本（从 1 开始单调递增） */
  version: number
  writeId: string
  kind: string
  operator: string
  summary: string
  at: string
}

/** 乐观锁失败的后到写入：内容与依据版本一并保留，不覆盖已生效数据 */
export interface ConflictDraft {
  id: string
  anomalyId: string
  writeId: string
  kind: string
  operator: string
  /** 后到审阅人保存时所见的版本 */
  baseVersion: number
  /** 冲突时已经生效的版本，即后到写入缺失的依据 */
  currentVersion: number
  reason: string
  payload: Record<string, unknown>
  createdAt: string
  resolved: boolean
}

/** 写入失败后留存的完整审阅版本，可原样重放恢复 */
export interface PendingWrite {
  writeId: string
  anomalyId: string
  kind: string
  baseVersion: number
  payload: Record<string, unknown>
  operator: string
  note: string
  /** 动作实际发生时间（窗口内时间戳），重放时沿用，保证留痕一致 */
  at: string
  failedAt: string
  lastError: string
  attempts: number
}

export interface Anomaly {
  id: string
  pointId: string
  title: string
  severity: Severity
  status: AnomalyStatus
  openedAt: string
  owner: string
  triggerReadingId: string
  observedValue: string
  fieldReviews: FieldReview[]
  opinions: ExpertOpinion[]
  plan: DispositionPlan
  /** 已失效/被替换的方案归档，含其签批与依据 */
  planHistory: DispositionPlan[]
  /** 同一版本链：异常 + 现场复核 + 专业意见 + 处置方案 + 审计动作 */
  revisions: RevisionRef[]
  conflictDrafts: ConflictDraft[]
  closedAt: string
  version: number
}

export interface AuditEntry {
  id: string
  entityId: string
  action: string
  operator: string
  detail: string
  createdAt: string
  /** 该动作落地后的链版本（所见版本在动作详情中体现） */
  version?: number
  writeId?: string
}

export interface TailingsDataset {
  points: MonitoringPoint[]
  thresholds: Threshold[]
  readings: RawReading[]
  anomalies: Anomaly[]
  audit: AuditEntry[]
  /** 失败待恢复的完整审阅版本（随审阅包导出，可从该版本恢复重试） */
  pendingWrites: PendingWrite[]
}
